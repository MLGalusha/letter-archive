#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, '..');
const sourcePath = path.join(
  rootDir,
  'backend/src/contracts/admin-wire-contracts.ts',
);
const mirrorPath = path.join(
  rootDir,
  'frontend/src/contracts/admin-wire-contracts.generated.ts',
);
const generatedHeader = `// Generated by scripts/sync-admin-wire-contracts.mjs.
// Source: backend/src/contracts/admin-wire-contracts.ts. Do not edit this mirror.

`;

const mode = process.argv[2];
if (mode !== '--check' && mode !== '--write') {
  process.stderr.write(
    'Usage: node scripts/sync-admin-wire-contracts.mjs --check|--write\n',
  );
  process.exit(2);
}

const source = await readFile(sourcePath, 'utf8');
if (/^\s*import(?:\s|\{)/m.test(source)) {
  process.stderr.write(
    'Admin wire contracts must remain dependency-free for the browser mirror.\n',
  );
  process.exit(1);
}

const expected = `${generatedHeader}${source}`;

if (mode === '--write') {
  await writeFile(mirrorPath, expected, 'utf8');
  process.stdout.write('Updated frontend admin wire-contract mirror.\n');
  process.exit(0);
}

let actual;
try {
  actual = await readFile(mirrorPath, 'utf8');
} catch (error) {
  if (error && typeof error === 'object' && error.code === 'ENOENT') {
    actual = '';
  } else {
    throw error;
  }
}

if (actual !== expected) {
  process.stderr.write(
    'Frontend admin wire contracts are stale. Run '
      + '`node scripts/sync-admin-wire-contracts.mjs --write`.\n',
  );
  process.exit(1);
}

process.stdout.write('Frontend admin wire contracts match the backend source.\n');
